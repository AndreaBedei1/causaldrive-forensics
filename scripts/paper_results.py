#!/usr/bin/env python3
"""The paper's tables and figures, built from the campaign's result files (privileged: evaluation side).

    python scripts/paper_results.py [--out results]

Reads only result files written by the other scripts (no reconstruction is run): the canonical runs'
reconstructions and evaluations (``traces/``), the campaign fusion metrics (``traces/fusion_metrics.json``),
the sweep summaries (``results/sweeps/``), the robustness study (``results/robustness/``) and the semantic
evaluation (``results/semantics/``).  Writes ``<out>/tables/<name>.{csv,md,tex}`` (LaTeX: booktabs) and
``<out>/figures/<name>.{svg,pdf}`` (fonts kept as text in the SVG, TrueType in the PDF), and an index
``<out>/README.md`` with the provenance of every input.  A missing input skips its table or figure (named in
the index).  ``scripts/results_qa.py`` checks the outputs.
"""

