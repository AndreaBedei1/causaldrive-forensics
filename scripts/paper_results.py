def table_campaign(t: Tables) -> None:
    rows = []
    for run in _canonical_runs():
        evaluation_path = run / "reconstruction" / "evaluation" / "evaluation.json"
        if not evaluation_path.exists():
            continue
        evaluation = _read(evaluation_path)
        recorders = sorted(p.name for p in (run / "vehicles").iterdir() if (p / "ego.jsonl").exists())
        participants = sorted({json.loads(line)["participant_id"] for line in
                               (run / "ground_truth" / "states.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()})
        between = [c for c in evaluation["collisions"] if "static/unrecorded" not in c["participants"]]
        aligned = [a for a in evaluation["alignment"] if a["status"] == "ALIGNED"]
        errors = [abs(a["error_s"]) for a in aligned if a.get("error_s") is not None]
        methods = sorted({a["method"] for a in aligned if a.get("method")})
        decided = [r for r in evaluation["tracks"] if r["status"] == "ASSOCIATED"]
        entities = _read(run / "reconstruction" / "global" / "anonymous_entities.json").get("entities", [])
        rows.append(["{0}/{1}".format(run.parent.name, run.name.replace("run_0_", "")), " ".join(recorders),
                     " ".join(p for p in participants if p not in recorders) or "-",
                     "{0}/{1}".format(sum(bool(c["participants_correct"]) for c in between), len(between)),
                     "{0}/{1}".format(len(aligned), len(evaluation["alignment"])),
                     ", ".join(m.replace("matched_collisions", "collision").replace("observed_trajectories", "observed")
                               .replace("reference_recorder", "reference") for m in methods) or "-",
                     max(errors) if errors else None,
                     "{0}/{1}".format(sum(r["verdict"] == "correct" for r in decided), len(decided)),
                     len(entities), evaluation["event_timing"]["max_abs_error_s"]])
    t.write("T1_canonical_runs", "Canonical runs: recorders, road users that recorded nothing, and what the reconstruction "
            "recovered (privileged evaluation).",
            ["run", "recorders", "unrecorded", "contacts recon./true", "aligned", "alignment", "max |offset err.| [s]",
             "identities correct/decided", "anonymous entities", "max |t_global err.| [s]"], rows,
            "Alignment: by matched collisions, by observed trajectories, or the reference recorder's own clock (no "
            "matched collision).  Errors against simulator time (privileged).",
            [0, 0, 0, 0, 0, 0, 3, 0, 0, 3])


def _sweep(name: str) -> Optional[Dict[str, Any]]:
    path = ROOT / "results" / "sweeps" / (name + ".json")
    return _read(path) if path.exists() else None


def _median(values: Sequence[Optional[float]]) -> Optional[float]:
    values = [v for v in values if v is not None]
    return statistics.median(values) if values else None


def _p95(values: Sequence[Optional[float]]) -> Optional[float]:
    values = sorted(v for v in values if v is not None)
    if not values:
        return None
    return values[min(len(values) - 1, int(math.ceil(0.95 * len(values))) - 1)]


