def figure_timeline(out: Path, written: List[Tuple[str, str]], run: Optional[Path] = None) -> None:
    run = run or ROOT / 'traces' / 'S17' / 'run_0_crash'
    """Per-vehicle event graph of one run on t_global: what each recorder's sensors established about each road
    user, its own actions, and (privileged overlay) when ground truth puts the same events."""
    graph_path = run / "reconstruction" / "global" / "global_graph.json"
    if not graph_path.exists():
        return
    from cdf.evaluation.worked_example import steering_onset
    plt = _style()
    graph = _read(graph_path)
    alignment = _read(run / "reconstruction" / "global" / "alignment.json")
    offsets = {name: clock.get("offset_to_global") for name, clock in alignment["graphs"].items()}
    oracle_path = run / "reconstruction" / "evaluation" / "event_oracle.json"
    oracle = _read(oracle_path) if oracle_path.exists() else None
    evaluation = _read(run / "reconstruction" / "evaluation" / "evaluation.json")
    nodes = [n for n in graph["nodes"] if n.get("t_global") is not None]
    recorders = sorted(offsets)
    lanes: List[Tuple[str, Optional[str]]] = []
    for owner in recorders:
        lanes.append((owner, None))
        subjects = sorted({n["subject_id"] for n in nodes if n.get("actor_id") == owner and n.get("subject_id")})
        lanes += [(owner, s) for s in subjects]
    index = {lane: i for i, lane in enumerate(lanes)}
    fig, ax = plt.subplots(figsize=(DOUBLE_COLUMN_IN, 0.42 * len(lanes) + 0.9))
    colours = {"CRITICAL_TTC": "tab:red", "CUT_IN_FROM_RIGHT": "tab:orange", "CUT_IN_FROM_LEFT": "tab:orange",
               "EGO_PATH": "tab:blue", "BRAKE": "black", "TRACK": "0.85"}
    heights = {"TRACK": 0.6, "CRITICAL_TTC": 0.42, "CUT_IN_FROM_RIGHT": 0.26, "CUT_IN_FROM_LEFT": 0.26, "EGO_PATH": 0.12,
               "BRAKE": 0.42}
    t_end = max(n["t_global"] for n in nodes)
    t_start = min(n["t_global"] for n in nodes)

    def spans(owner: str, subject: Optional[str], start: str, end: str) -> List[Tuple[float, float]]:
        out, open_t = [], None
        for n in sorted((n for n in nodes if n.get("actor_id") == owner and n.get("subject_id") == subject),
                        key=lambda n: n["t_global"]):
            if n["event_type"] == start or (start == "TRACK_APPEARED" and n["event_type"].startswith("TRACK_APPEARED")):
                open_t = n["t_global"] if open_t is None else open_t
            elif n["event_type"] == end and open_t is not None:
                out.append((open_t, n["t_global"]))
                open_t = None
        if open_t is not None:
            out.append((open_t, t_end))
        return out

    for (owner, subject), y in index.items():
        if subject is None:
            for a, b in spans(owner, None, "BRAKE_START", "BRAKE_END"):
                ax.barh(y, b - a, left=a, height=heights["BRAKE"], color=colours["BRAKE"], alpha=0.8)
            clock_origin = None
            local_graph = run / "reconstruction" / owner / "local_graph.json"
            if local_graph.exists():
                clock_origin = float(_read(local_graph)["recorder"]["clock"]["origin_source_timestamp"])
            steer = None if clock_origin is None else steering_onset(run / "vehicles" / owner / "controls.jsonl", clock_origin,
                                                                       after=0.0)
            if steer is not None and offsets.get(owner) is not None:
                ax.plot([steer + offsets[owner]], [y], marker=">", color="tab:green", markersize=6, linestyle="none")
            continue
        for a, b in spans(owner, subject, "TRACK_APPEARED", "TRACK_LOST"):
            ax.barh(y, b - a, left=a, height=heights["TRACK"], color=colours["TRACK"])
        # Wider bars first, so that the narrower ones stay visible on top.
        for key, start, end in (("CRITICAL_TTC", "CRITICAL_TTC_START", "CRITICAL_TTC_END"),
                                ("CUT_IN_FROM_RIGHT", "CUT_IN_FROM_RIGHT_START", "CUT_IN_FROM_RIGHT_END"),
                                ("CUT_IN_FROM_LEFT", "CUT_IN_FROM_LEFT_START", "CUT_IN_FROM_LEFT_END"),
                                ("EGO_PATH", "EGO_PATH_ENTRY", "EGO_PATH_EXIT")):
            for a, b in spans(owner, subject, start, end):
                ax.barh(y, b - a, left=a, height=heights[key], color=colours[key], alpha=0.85)
    collision = [n["t_global"] for n in nodes if n["event_type"] == "COLLISION"]
    for t in collision:
        ax.axvline(t, color="black", linewidth=0.8, linestyle="--")
    # Privileged overlay: when ground truth (all-seeing oracle) puts each recorder's CRITICAL_TTC_START.
    if oracle is not None:
        # The lane of a true subject: the global entity of the observer's tracks of it (privileged mapping).
        identity = {row["track"]: row.get("true_identity") for row in evaluation["tracks"]}
        names: Dict[Tuple[str, str], str] = {}
        for item in _read(run / "reconstruction" / "global" / "associations.json"):
            true = identity.get("{0}:{1}".format(item["local_graph"], item["local_track"]))
            if true and item.get("global_entity"):
                names.setdefault((item["local_graph"], true), item["global_entity"])
        for owner, events in oracle["events"]["PERFECT"].items():
            if offsets.get(owner) is None:
                continue
            for e in events:
                if e["type"] != "CRITICAL_TTC_START":
                    continue
                subject = e["subject"] if e["subject"] in recorders else names.get((owner, e["subject"]))
                lane = index.get((owner, subject))
                if lane is None:
                    continue
                t = e["t_local"] + offsets[owner]
                ax.plot([t, t], [lane - 0.3, lane + 0.3], color="black", linewidth=1.6)
    ax.set_yticks(range(len(lanes)))
    ax.set_yticklabels(["{0}: own actions".format(o) if s is None else "{0} perceives {1}".format(o, s) for o, s in lanes])
    ax.invert_yaxis()
    ax.set_xlim(t_start - 0.2, min(t_end, (collision[0] if collision else t_end) + 1.5))
    ax.set_xlabel("t_global [s] (0 = reference collision)")
    from matplotlib.patches import Patch
    from matplotlib.lines import Line2D
    handles = [Patch(color=colours["TRACK"], label="tracked by radar"), Patch(color=colours["EGO_PATH"], label="in ego path"),
               Patch(color=colours["CUT_IN_FROM_RIGHT"], label="cut-in"), Patch(color=colours["CRITICAL_TTC"], label="CRITICAL_TTC"),
               Patch(color=colours["BRAKE"], label="braking"),
               Line2D([], [], marker=">", color="tab:green", linestyle="none", label="steering onset"),
               Line2D([], [], color="black", linewidth=1.6, label="CRITICAL_TTC start, ground truth (evaluation)"),
               Line2D([], [], color="black", linestyle="--", linewidth=0.8, label="collision")]
    ax.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.5, -0.16), ncol=4, frameon=False)
    ax.grid(axis="x", alpha=0.3)
    _save(fig, out, "F1_event_timeline_{0}".format(run.parent.name.lower()), written,
          "Per-vehicle event graph of {0} on t_global: what each recorder's own sensors established about each road "
          "user (U1: the road user that recorded nothing), its own actions, and where ground truth puts the start of "
          "each CRITICAL_TTC (privileged overlay).".format(run.parent.name))
    plt.close(fig)


def figure_alignment(out: Path, written: List[Tuple[str, str]]) -> None:
    plt = _style()
    data, labels = [], []
    canonical = []
    for run in _canonical_runs():
        path = run / "reconstruction" / "evaluation" / "evaluation.json"
        if path.exists() and _read(path)["event_timing"]["max_abs_error_s"] is not None:
            canonical.append(_read(path)["event_timing"]["max_abs_error_s"])
    if canonical:
        data.append(canonical)
        labels.append("canonical")
    for name in SWEEPS:
        sweep = _sweep(name)
        if sweep is None:
            continue
        values = [row["max_abs_t_global_error_s"] for row in sweep["rows"] if row["max_abs_t_global_error_s"] is not None]
        if values:
            data.append(values)
            labels.append(name.replace("anonymous_pair_", "pair ").replace("_", " "))
    if not data:
        return
    fig, ax = plt.subplots(figsize=(SINGLE_COLUMN_IN, 2.4))
    for i, values in enumerate(data):
        xs = [i + 0.15 * ((k % 7) - 3) / 3.0 for k in range(len(values))]
        ax.plot(xs, values, "o", markersize=2.5, alpha=0.7)
    ax.set_xticks(range(len(labels)))
    ax.set_xticklabels(labels, rotation=30, ha="right")
    ax.set_ylabel("max |t_global error| per run [s]")
    ax.axhline(0.05, color="grey", linewidth=0.8, linestyle=":")
    ax.grid(axis="y", alpha=0.3)
    _save(fig, out, "F2_alignment_errors", written,
          "Largest event-time error on t_global per run (privileged evaluation); dotted: one radar period (0.05 s).")
    plt.close(fig)


def figure_fusion(out: Path, written: List[Tuple[str, str]]) -> None:
    plt = _style()
    rows = []
    for name in SWEEPS:
        sweep = _sweep(name)
        if sweep is None:
            continue
        pairs = [(row["fused_centre_error_median_m"], row["single_track_centre_error_median_m"]) for row in sweep["rows"]
                 if row["fused_centre_error_median_m"] is not None and row["single_track_centre_error_median_m"] is not None]
        if pairs:
            rows.append((name.replace("anonymous_pair_", "pair ").replace("_", " "), pairs))
    if not rows:
        return
    fig, ax = plt.subplots(figsize=(SINGLE_COLUMN_IN, 2.4))
    for i, (label, pairs) in enumerate(rows):
        fused = [a for a, _ in pairs]
        single = [b for _, b in pairs]
        parts = ax.boxplot([fused, single], positions=[3 * i, 3 * i + 1], widths=0.8, patch_artist=True,
                           flierprops={"markersize": 2})
        for patch, colour in zip(parts["boxes"], ("tab:blue", "0.7")):
            patch.set_facecolor(colour)
    ax.set_xticks([3 * i + 0.5 for i in range(len(rows))])
    ax.set_xticklabels([label for label, _ in rows], rotation=30, ha="right")
    ax.set_ylabel("centre error, run median [m]")
    from matplotlib.patches import Patch
    ax.legend(handles=[Patch(color="tab:blue", label="fused"), Patch(color="0.7", label="single-track nominal box")],
              loc="lower left", bbox_to_anchor=(0.0, 1.02), ncol=2)
    ax.grid(axis="y", alpha=0.3)
    _save(fig, out, "F3_fusion_centre_error", written,
          "Centre error of the road users that recorded nothing, per sweep run: fused estimate against the single-track "
          "nominal box at the same instants (privileged evaluation).")
    plt.close(fig)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=ROOT / "results")
    args = parser.parse_args(argv)
    from cdf.evaluation.provenance import provenance
    from cdf.reconstruction.config import load_config
    tables = Tables(args.out)
    for build in (table_campaign, table_sweeps, table_fusion, table_fusion_sweeps, table_oracle, table_robustness,
                  table_sensitivity, table_impulse, table_body_ablation, table_pose_and_combined):
        build(tables)
    figures: List[Tuple[str, str]] = []
    for build in (figure_timeline, figure_alignment, figure_fusion):
        build(args.out / "figures", figures)
    existing = sorted(str(p.relative_to(args.out)).replace("\\", "/") for p in args.out.glob("*/figures/*.pdf"))
    prov = provenance(load_config().to_dict(), [])
    import hashlib
    digest = hashlib.sha256()
    for source in sorted((ROOT / 'scripts').glob('*.py')):
        digest.update(source.relative_to(ROOT).as_posix().encode('utf-8') + b'\0')
        digest.update(source.read_bytes().replace(b'\r\n', b'\n') + b'\0')
    prov['analysis_scripts_sha256'] = digest.hexdigest()
    prov['scope'] = 'All tables and figures generated from studies executed at the same clean analysis freeze'
    inputs = sorted({p for folder in ('sweeps', 'semantics', 'robustness')
                     for p in (ROOT / 'results' / folder).glob('*.json')}
                    | {ROOT / 'traces' / 'fusion_metrics.json'}
                    | {p for run in _canonical_runs() for p in (run / 'reconstruction').rglob('*')
                       if p.suffix in ('.json', '.jsonl')})
    prov['inputs'] = {}
    for path in inputs:
        item = {'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
        if path.suffix == '.json':
            record = _read(path)
            if isinstance(record, dict):
                for key in ('provenance', 'family_provenance', 'scope'):
                    if key in record:
                        item[key] = record[key]
        prov['inputs'][path.relative_to(ROOT).as_posix()] = item
    # Matplotlib writes whitespace after SVG path coordinates; normalize it
    # before hashing the deliverables, without changing the vector geometry.
    for path in args.out.rglob('*.svg'):
        path.write_text('\n'.join(line.rstrip() for line in path.read_text(encoding='utf-8').splitlines()) + '\n',
                        encoding='utf-8')
    prov['artifacts'] = {p.relative_to(args.out).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                         for p in sorted(args.out.rglob('*'))
                         if p.is_file() and (p.suffix in ('.pdf', '.svg') or p.parent.name == 'tables')}
    (args.out / 'artifact_provenance.json').write_text(json.dumps(prov,indent=2)+'\n',encoding='utf-8')
    index = ["# Paper results", "",
             "Generated by `scripts/paper_results.py` from the campaign's result files (privileged evaluation; nothing "
             "here is an input of the reconstruction).  Checked by `scripts/results_qa.py`.  Provenance: code `{0}`, "
             "configuration `{1}`, commit `{2}`{3}, {4}.".format(prov["code_sha256"][:16], prov["config_sha256"][:16],
                                                               prov["git_commit"], " (uncommitted changes)" if prov["git_dirty"] else "",
                                                               prov["generated_utc"]), "",
             "## Tables (`tables/<name>.csv|md|tex`)", ""]
    index += ["- `{0}`: {1}".format(name, caption) for name, caption in tables.written]
    index += ["", "## Figures (`figures/<name>.svg|pdf`)", ""]
    index += ["- `{0}`: {1}".format(name, caption) for name, caption in figures]
    index += ["", "## Figures of the studies", ""] + ["- `{0}`".format(p) for p in existing]
    index += ["", "## Inputs", "",
              "- canonical runs: `traces/S*/run_*/reconstruction/` (evaluation, event_oracle.json) and `traces/fusion_metrics.json`",
              "- sweeps: `results/sweeps/<sweep>.json` (raw runs under `sweeps/`, not in the repository)",
              "- robustness: `results/robustness/summary.json`, `impulse_symmetry.json`",
              "- semantics: `results/semantics/event_oracle_<label>.json`, `sensitivity_<label>.json`"]
    index += ['', '## Analysis scope and provenance', '',
              'All 17 canonical runs, 240 saved sweeps, robustness families and semantic sensitivity were rerun offline',
              'from the same clean analysis freeze. Acquisition provenance remains historical and unchanged.',
              'The table/figure rendering snapshot is in `artifact_provenance.json` (source and script hashes, clean execution commit).',
              'See `docs/FINAL_VALIDATION_REPORT.md` for metrics, limitations and the analysis freeze commit.']
    (args.out / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print("\n".join(index))
    return 0


