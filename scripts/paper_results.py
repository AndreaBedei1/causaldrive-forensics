def table_robustness(t: Tables) -> None:
    path = ROOT / "results" / "robustness" / "summary.json"
    if not path.exists():
        return
    record = _read(path)

    def mean_sd(row: Dict[str, Any], key: str, decimals: int) -> str:
        value, sd = row.get(key), row.get(key + "_sd")
        if value is None:
            return "-"
        return "{0:.{2}f}".format(value, sd, decimals) + ("" if not sd else " +- {0:.{1}f}".format(sd, decimals))

    rows = []
    displayed = list(record['rows'])
    for row in displayed:
        errors = None
