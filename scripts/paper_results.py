def _read(path: Path) -> Any:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _canonical_runs() -> List[Path]:
    return sorted(p for p in (ROOT / "traces").glob("S*/run_*") if (p / "reconstruction" / "global").exists())


def _fmt(value: Any, decimals: int = 2) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "-"
    if isinstance(value, (int,)) and not isinstance(value, bool):
        return str(value)
    if isinstance(value, float):
        return "{0:.{1}f}".format(value, decimals)
    return str(value)


def _tex(text: str) -> str:
    for a, b in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_"),
                 ("+-", "$\\pm$"), ("<=", "$\\le$"), (">=", "$\\ge$")):
        text = text.replace(a, b)
    return text


class Tables:
    def __init__(self, out: Path) -> None:
        self.dir = out / "tables"
        self.dir.mkdir(parents=True, exist_ok=True)
        self.written: List[Tuple[str, str]] = []

    def write(self, name: str, caption: str, columns: Sequence[str], rows: Sequence[Sequence[Any]],
              notes: str = "", decimals: Optional[Sequence[int]] = None) -> None:
        decimals = list(decimals or [2] * len(columns))
        cells = [[_fmt(v, decimals[i]) for i, v in enumerate(row)] for row in rows]
        with (self.dir / (name + ".csv")).open("w", newline="", encoding="utf-8") as handle:
            writer = csv.writer(handle)
            writer.writerow(columns)
            writer.writerows(cells)
        md = ["**{0}.**  {1}".format(name, caption), "", "| " + " | ".join(columns) + " |",
              "|" + "|".join("---" for _ in columns) + "|"]
        md += ["| " + " | ".join(row) + " |" for row in cells]
        if notes:
            md += ["", notes]
        (self.dir / (name + ".md")).write_text("\n".join(md) + "\n", encoding="utf-8")
        align = "l" + "r" * (len(columns) - 1)
        tex = ["% generated by scripts/paper_results.py; do not edit", "\\begin{table}[t]", "\\centering",
               "\\caption{" + _tex(caption) + "}", "\\label{tab:" + name + "}", "\\footnotesize",
               "\\begin{tabular}{" + align + "}", "\\toprule",
               " & ".join(_tex(c) for c in columns) + " \\\\", "\\midrule"]
        tex += [" & ".join(_tex(c) for c in row) + " \\\\" for row in cells]
        tex += ["\\bottomrule", "\\end{tabular}"]
        if notes:
            tex += ["\\par\\smallskip\\parbox{\\linewidth}{\\scriptsize " + _tex(notes) + "}"]
        tex += ["\\end{table}"]
        (self.dir / (name + ".tex")).write_text("\n".join(tex) + "\n", encoding="utf-8")
        self.written.append((name, caption))


def _style():
    from cdf.evaluation.figures import paper_style
    return paper_style()


def _save(fig: Any, out: Path, name: str, written: List[Tuple[str, str]], caption: str) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for suffix in ("svg", "pdf"):
        fig.savefig(str(out / "{0}.{1}".format(name, suffix)), bbox_inches="tight")
    written.append((name, caption))


